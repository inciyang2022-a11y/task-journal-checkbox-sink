export const TRANSLATIONS: Record<SupportedLanguage, TranslationDictionary> = {
	'zh-CN': ZH_CN_TRANSLATIONS,
	en: EN_TRANSLATIONS,
};

export function resolveLanguage(
	setting: LanguageSetting,
	appLanguage: string | null | undefined,
): SupportedLanguage {
	if (setting !== 'auto') {
		return setting;
	}

	const normalized = appLanguage?.trim().toLowerCase();
	return normalized === 'zh' || normalized === 'zh-cn' ? 'zh-CN' : 'en';
}

export function translate(
	language: SupportedLanguage,
	key: TranslationKey,
	values: Record<string, string | number> = {},
): string {
	return Object.entries(values).reduce(
		(result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
		TRANSLATIONS[language][key],
	);
}

export function getLocalizedDefaultHeadings(language: SupportedLanguage): {
	dailyNoteHeading: string;
	archiveHeading: string;
} {
	return language === 'zh-CN'
		? {
			dailyNoteHeading: '## 任务记录',
			archiveHeading: '## 已完成任务归档',
		}
		: {
			dailyNoteHeading: '## Task journal',
			archiveHeading: '## Completed tasks archive',
		};
}
